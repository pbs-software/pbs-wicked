SET NOCOUNT ON;

-- 1. Identify valid VRNs that caught the target species (Pre-filtered with HAVING)
SELECT 
	MC.VESSEL_REGISTRATION_NUMBER, -- Keep the raw column for faster indexing/joining
	CONVERT(VARCHAR(50), REPLACE(ISNULL(MC.VESSEL_REGISTRATION_NUMBER, '0'), 'i', '1')) AS VRN_CLEAN
INTO #SPP_VESSELS
FROM GFFOS.dbo.GF_MERGED_CATCH MC
WHERE MC.VESSEL_REGISTRATION_NUMBER IS NOT NULL
GROUP BY MC.VESSEL_REGISTRATION_NUMBER
HAVING SUM(CASE WHEN MC.SPECIES_CODE IN (@sppcode) THEN 1 ELSE 0 END) > 0;

-- Create an index on our temp table to speed up the next step
CREATE CLUSTERED INDEX IX_SPP_VESSELS_VRN ON #SPP_VESSELS(VESSEL_REGISTRATION_NUMBER);

-- 2. Identify all fishing events for those vessels (Removed ORDER BY, kept IDs as integers)
SELECT 
	MC.FISHING_EVENT_ID, -- Keep as INT for join performance
	ISNULL(TS.SUCCESS_CODE, 0) AS SUCCESS_CODE,
	SUM(ISNULL(MC.LANDED_KG, 0) + ISNULL(MC.DISCARDED_KG, 0)) AS TCAT
INTO #SPP_FEID
FROM GFFOS.dbo.GF_MERGED_CATCH MC
INNER JOIN #SPP_VESSELS SV 
	ON MC.VESSEL_REGISTRATION_NUMBER = SV.VESSEL_REGISTRATION_NUMBER -- SARGABLE JOIN
LEFT OUTER JOIN GFFOS.dbo.GF_FE_TRAWL_SPECS TS 
	ON MC.FISHING_EVENT_ID = TS.FISHING_EVENT_ID
GROUP BY MC.FISHING_EVENT_ID, ISNULL(TS.SUCCESS_CODE, 0);

-- Create index on the event ID temp table
CREATE CLUSTERED INDEX IX_SPP_FEID_FEID ON #SPP_FEID(FISHING_EVENT_ID);

-- 3. Main Query (Using SARGABLE expressions)
SELECT
	YEAR(C.BEST_DATE) AS [YEAR],
	CONVERT(VARCHAR(19), C.BEST_DATE, 20) AS BEST_DATE,
	C.VESSEL_NAME,
	SV.VRN_CLEAN AS VESSEL_REGISTRATION_NUMBER, -- Pulled pre-cleaned data from our temp table
	C.FISHERY_SECTOR,
	C.TRIP_ID,
	C.FISHING_EVENT_ID,
	CONVERT(VARCHAR(19), C.FE_START_DATE, 20) AS FE_START_DATE,
	CONVERT(VARCHAR(19), C.FE_END_DATE, 20) AS FE_END_DATE,
	@sppcode AS SPECIES_CODE,
	C.GEAR,
	C.BEST_DEPTH,
	C.MAJOR_STAT_AREA_CODE,
	C.MINOR_STAT_AREA_CODE,
	C.LOCALITY_CODE,
	C.LATITUDE,
	C.LONGITUDE,
	SUM(CASE WHEN C.SPECIES_CODE IN (@sppcode) THEN ISNULL(C.LANDED_KG, 0) ELSE 0 END) AS LANDED_KG,
	SUM(CASE WHEN C.SPECIES_CODE IN (@sppcode) THEN ISNULL(C.DISCARDED_KG, 0) ELSE 0 END) AS DISCARDED_KG,
	SUM(CASE WHEN C.SPECIES_CODE IN (@sppcode) THEN ISNULL(C.LANDED_KG, 0) + ISNULL(C.DISCARDED_KG, 0) ELSE 0 END) AS CATCH_KG
INTO #SPP_RECS
FROM GFFOS.dbo.GF_MERGED_CATCH C
INNER JOIN #SPP_FEID SF 
	ON SF.FISHING_EVENT_ID = C.FISHING_EVENT_ID -- Matching numeric IDs directly
INNER JOIN #SPP_VESSELS SV 
	ON C.VESSEL_REGISTRATION_NUMBER = SV.VESSEL_REGISTRATION_NUMBER -- Grab pre-calculated VRN cleanup
INNER JOIN GFFOS.dbo.SPECIES S 
	ON S.SPECIES_CODE = C.SPECIES_CODE
WHERE
	C.BEST_DATE >= '1996-01-01' AND -- Sargable index date-range filter
--	C.GEAR IN ('MIDWATER TRAWL') AND 
	C.GEAR IN (@gear) AND 
	C.MAJOR_STAT_AREA_CODE IN (@major) AND
	SF.TCAT > 0 AND  
	SF.SUCCESS_CODE <= 11711 
GROUP BY
	C.BEST_DATE,
	C.VESSEL_NAME,
	SV.VRN_CLEAN,
	C.FISHERY_SECTOR,
	C.TRIP_ID,
	C.FISHING_EVENT_ID,
	C.FE_START_DATE,
	C.FE_END_DATE,
	C.GEAR,
	C.BEST_DEPTH,
	C.MAJOR_STAT_AREA_CODE,
	C.MINOR_STAT_AREA_CODE,
	C.LOCALITY_CODE,
	C.LATITUDE,
	C.LONGITUDE;

select * from #SPP_RECS

